# Set
numbers = {10, 20, 30, 20}
print("Set:", numbers)

# Dictionary
student = {
    "name": "Rudra",
    "age": 22,
    "course": "Python"
}
print("Dictionary:", student)

# Boolean
a = 10
b = 20
print("a > b:", a > b)
print("a < b:", a < b)

# None
result = None
print("Result:", result)
print("Type:", type(result))

# Implicit type conversion
x = 10
y = 5.5
z = x + y

print("Implicit conversion:", z)
print("Type:", type(z))

# Explicit type conversion
num = "100"
num = int(num)

print("Explicit conversion:", num)
print("Type:", type(num))

# Float to integer
price = 99.99
price = int(price)

print("Converted price:", price)

# Integer to string
age = 22
age = str(age)

print("Age:", age)
print("Type:", type(age))

